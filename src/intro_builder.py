from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, Spacer, PageBreak
from common_styles import (
    BookmarkFlowable, style_title, style_h1, style_h2, style_body, style_bullet
)
from reportlab.lib.styles import ParagraphStyle

def build_intro(story):
    # =========================================================================
    # СТР. 5: ВВЕДЕНИЕ - Актуальность и теоретические предпосылки
    # =========================================================================
    p_body_intro = ParagraphStyle(
        'IntroBody',
        parent=style_body,
        fontSize=11.5,
        leading=15,
        spaceAfter=0
    )
    p_bullet_intro = ParagraphStyle(
        'IntroBullet',
        parent=style_bullet,
        fontSize=11,
        leading=14.5,
        leftIndent=14 * mm,
        firstLineIndent=-4 * mm,
        spaceAfter=1
    )

    story.append(BookmarkFlowable("intro"))
    story.append(Paragraph("ВВЕДЕНИЕ", style_title))

    story.append(Paragraph("Актуальность", style_h1))
    story.append(Paragraph(
        "В современную эпоху стремительного развития технологий искусственного интеллекта (ИИ) и машинного обучения "
        "(Machine Learning, ML) ключевым фактором успеха при решении прикладных задач становится не столько усложнение "
        "архитектуры нейросетей, сколько качество и глубина подготовки исходных информационных массивов. В индустриальной "
        "практике построения ИИ-систем прочно закрепился подход, ориентированный на данные (Data-Centric AI), постулирующий, "
        "что качество исходных данных напрямую определяет верхнюю границу точности и надежности математических моделей, "
        "в то время как алгоритм обучения является лишь инструментом извлечения заложенных в них закономерностей. "
        "Необработанные, «сырые» наборы данных практически всегда содержат аппаратные пропуски, экстремальные выбросы, "
        "синтаксический шум, аномалии и дисбаланс классов, что при попытке прямого обучения приводит к переобучению алгоритмов, "
        "искажению полезных трендов и, как следствие, к ошибочным предсказаниям на реальных производственных объектах. "
        "Первичный технический анализ и предобработка данных выступают обязательным фундаментом, превращающим разрозненные "
        "сведения в валидный цифровой актив.",
        p_body_intro
    ))
    story.append(Spacer(1, 1.5 * mm))
    story.append(Paragraph(
        "Прямая зависимость качества работы ИИ-моделей от уровня чистоты и структурированности входных данных многократно "
        "подтверждена фундаментальными экспериментальными исследованиями в мировом научном сообществе:",
        p_body_intro
    ))
    story.append(Paragraph(
        "• В исследовании по оценке загрязнения данных на примере классических алгоритмов (Random Forest, градиентный бустинг) "
        "доказано, что комплексная предобработка предотвращает падение точности моделей в среднем на 15–20% по сравнению "
        "с обучением на зашумленных массивах;",
        p_bullet_intro
    ))
    story.append(Paragraph(
        "• В прикладной работе по NLP авторами экспериментально продемонстрировано, что предварительная подготовка текстов "
        "(очистка regex, фильтрация стоп-слов, лемматизация) снижает ошибку признаков и повышает итоговую точность классификаторов на 5–8%.",
        p_bullet_intro
    ))
    story.append(Spacer(1, 1.5 * mm))
    story.append(Paragraph(
        "Современный специалист сталкивается с колоссальным многообразием модальностей наборов данных: табличные структуры (.csv, .xlsx), "
        "хронологические временные ряды датчиков (.csv, HDF5), растровые графические изображения (.jpg, .png) с аннотациями YOLO (.txt), "
        "а также неструктурированные текстовые массивы естественного языка. Уверенное владение фундаментальными навыками первичного анализа, "
        "визуализации и предобработки разнородных типов данных является критически важной компетенцией квалифицированного специалиста по данным. "
        "Без этого невозможно построение устойчивых, масштабируемых и надежных индустриальных систем искусственного интеллекта.",
        p_body_intro
    ))

    story.append(PageBreak())

    # =========================================================================
    # СТР. 6: Постановка задачи и структура работы
    # =========================================================================
    story.append(Paragraph("Постановка задачи", style_h1))
    story.append(Paragraph(
        "<b>Целью курсового проекта</b> является получение практических навыков по поиску и первичному анализу наборов данных "
        "разных типов по различным областям применения. Для достижения поставленной цели необходимо решить следующие задачи:",
        p_body_intro
    ))
    story.append(Paragraph(
        "1. Подготовить для каждого типа данных (табличные данные, временные ряды, изображения, тексты) краткое описание "
        "выбранной задачи, решение которой связано с применением технологий искусственного интеллекта;",
        p_bullet_intro
    ))
    story.append(Paragraph(
        "2. Подобрать для каждого типа данных набор данных из авторитетных открытых источников, необходимый для обучения "
        "ИИ-модели, решающей соответствующую выбранную задачу;",
        p_bullet_intro
    ))
    story.append(Paragraph(
        "3. Разработать и реализовать комплекс программ на языке Python, каждая из которых для заданного типа данных должна "
        "выполнять следующие основные функции первичного анализа: загрузка и визуализация данных, статистический анализ, "
        "выявление специфических особенностей для определенного типа данных;",
        p_bullet_intro
    ))
    story.append(Paragraph(
        "4. Сформулировать выводы по каждому этапу анализа, а также итоговое заключение о качестве данных и их пригодности "
        "для решения поставленной задачи;",
        p_bullet_intro
    ))
    story.append(Paragraph(
        "5. Разместить исходный код в открытом репозитории системы контроля версий Git.",
        p_bullet_intro
    ))
    story.append(Spacer(1, 2 * mm))

    story.append(Paragraph("Структура и содержание работы", style_h1))
    story.append(Paragraph(
        "Работа состоит из введения, четырех разделов, заключения и списка литературы. Объем работы составляет 48 страниц, "
        "объем списка литературы – 9 источников.",
        p_body_intro
    ))
    story.append(Spacer(1, 1.5 * mm))
    story.append(Paragraph(
        "В первом разделе исследуется набор структурированных табличных данных на примере задачи прогнозирования стоимости "
        "медицинского страхования (Кейс №58, ОГБУ «ЧРЦНИТ»), где выполняются статистический аудит, оценка распределений признаков "
        "и корреляционный анализ.",
        p_body_intro
    ))
    story.append(Spacer(1, 1.5 * mm))
    story.append(Paragraph(
        "Второй раздел посвящен первичному анализу многомерных временных рядов на основе показаний промышленного кориолисового "
        "расходомера (Кейс №60, ПАО «Северсталь» / TUV-NEL), включая сглаживание трендов скользящим средним и изоляцию "
        "высокочастотных измерительных шумов.",
        p_body_intro
    ))
    story.append(Spacer(1, 1.5 * mm))
    story.append(Paragraph(
        "В третьем разделе выполняется аудит графических наборов данных для компьютерного зрения в рамках контроля техники "
        "безопасности на производстве (Кейс №48, ПАО «ЧКПЗ»), где оценивается баланс целевых классов СИЗ и анализируются "
        "геометрические параметры разметки YOLO.",
        p_body_intro
    ))
    story.append(Spacer(1, 1.5 * mm))
    story.append(Paragraph(
        "В четвертом разделе представлено исследование русскоязычного текстового корпуса обращений граждан (Кейс №68, "
        "ПАО «Сбербанк» / ОГБУ «ЧРЦНИТ»), включающее синтаксическую очистку, морфологическую лемматизацию, расчет весов TF-IDF "
        "и реализацию алгоритма семантического поиска по косинусному сходству.",
        p_body_intro
    ))
    story.append(Spacer(1, 1.5 * mm))
    story.append(Paragraph(
        "В заключении подводятся итоги курсового проекта и формулируются обобщающие выводы о метрологической пригодности данных.",
        p_body_intro
    ))

    story.append(PageBreak())
